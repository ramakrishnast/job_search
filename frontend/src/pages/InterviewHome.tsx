import { useState } from "react";
import { Link, useNavigate } from "react-router-dom";
import { useMutation, useQuery } from "@tanstack/react-query";
import { Play } from "lucide-react";
import { api, fmtDate, KIND_LABELS, qs, type JobSummary, type Session, type Status } from "../api";
import { Badge, Button, Card, cx, Empty, ErrorBox, Field, inputCls } from "../components/ui";

const KINDS = [
  { k: "system_design", d: "RAG at scale, multi-agent systems, eval pipelines — with a whiteboard." },
  { k: "ml_fundamentals", d: "Transformers, attention, fine-tuning vs RAG, quantization, evals, hallucinations." },
  { k: "behavioral", d: "STAR answers grounded in your story bank; the interviewer probes for specifics." },
  { k: "coding", d: "Python + LLM-API problems with a code editor and real test runs." },
  { k: "company", d: "A tailored loop generated from a job description in your pipeline." },
];

export default function InterviewHome() {
  const nav = useNavigate();
  const [kind, setKind] = useState("system_design");
  const [cfg, setCfg] = useState({ difficulty: "", num_questions: 3, timer: "", max_followups: 2, job_id: "" });
  const { data: status } = useQuery({ queryKey: ["status"], queryFn: () => api.get<Status>("/status") });
  const { data: sessions } = useQuery({ queryKey: ["interviews"], queryFn: () => api.get<Session[]>("/interviews") });
  const { data: jobs } = useQuery({
    queryKey: ["jobs", "for-loop"],
    queryFn: () => api.get<{ jobs: JobSummary[] }>("/jobs" + qs({ matching: false, status: "all", limit: 300, sort: "score" })),
    enabled: kind === "company",
  });
  const start = useMutation({
    mutationFn: () =>
      api.post<Session>("/interviews", {
        kind,
        difficulty: cfg.difficulty ? Number(cfg.difficulty) : null,
        num_questions: cfg.num_questions,
        timer_seconds: cfg.timer ? Number(cfg.timer) * 60 : null,
        max_followups: cfg.max_followups,
        job_id: kind === "company" ? Number(cfg.job_id) : null,
      }),
    onSuccess: (s) => nav(`/interview/${s.id}`),
  });
  const pipelineJobs = jobs?.jobs.filter((j) => j.stage) ?? [];
  return (
    <div className="space-y-4">
      <h1 className="text-xl font-semibold">Mock interview</h1>
      {!status?.llm.configured && <ErrorBox error="Live interviews need OPENAI_API_KEY in .env (the interviewer, follow-ups and scorecards are generated by the LLM). You can still practice coding problems against tests from the Question Bank." />}
      <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-5">
        {KINDS.map(({ k, d }) => (
          <button key={k} onClick={() => setKind(k)} className={cx("rounded-xl p-3 text-left ring-1 transition", kind === k ? "bg-brand-50 ring-brand-500 dark:bg-slate-800" : "bg-white ring-slate-200 hover:ring-slate-300 dark:bg-slate-900 dark:ring-slate-800")}>
            <div className="text-sm font-semibold">{KIND_LABELS[k]}</div>
            <div className="mt-1 text-xs text-slate-500">{d}</div>
          </button>
        ))}
      </div>
      <Card>
        <div className="flex flex-wrap items-end gap-3">
          {kind === "company" ? (
            <Field label="Job (from your pipeline)">
              <select className={inputCls + " w-80"} value={cfg.job_id} onChange={(e) => setCfg({ ...cfg, job_id: e.target.value })}>
                <option value="">Select a job…</option>
                {pipelineJobs.map((j) => <option key={j.id} value={j.id}>{j.company} — {j.title}</option>)}
              </select>
            </Field>
          ) : (
            <Field label="Difficulty">
              <select className={inputCls} value={cfg.difficulty} onChange={(e) => setCfg({ ...cfg, difficulty: e.target.value })}>
                <option value="">Mixed</option><option value="1">Easy</option><option value="2">Medium</option><option value="3">Hard</option>
              </select>
            </Field>
          )}
          <Field label="Questions"><input type="number" min={1} max={8} className={inputCls + " w-20"} value={cfg.num_questions} onChange={(e) => setCfg({ ...cfg, num_questions: Number(e.target.value) })} /></Field>
          <Field label="Timer per question (min)"><input type="number" min={1} max={60} placeholder="off" className={inputCls + " w-28"} value={cfg.timer} onChange={(e) => setCfg({ ...cfg, timer: e.target.value })} /></Field>
          <Field label="Max follow-ups"><input type="number" min={0} max={4} className={inputCls + " w-20"} value={cfg.max_followups} onChange={(e) => setCfg({ ...cfg, max_followups: Number(e.target.value) })} /></Field>
          <Button variant="primary" loading={start.isPending} disabled={kind === "company" && !cfg.job_id} onClick={() => start.mutate()}><Play className="h-4 w-4" /> Start interview</Button>
        </div>
        <p className="mt-2 text-xs text-slate-500">Questions due for spaced-repetition review and your weakest topics are picked first.</p>
        <ErrorBox error={start.error} />
      </Card>
      <Card title="Past sessions">
        {!sessions?.length ? <Empty>No sessions yet.</Empty> : (
          <table className="w-full text-sm">
            <thead className="text-left text-xs text-slate-500"><tr><th className="py-1">Date</th><th>Type</th><th>Status</th><th>Questions</th><th className="text-right">Score</th></tr></thead>
            <tbody>
              {sessions.map((s) => (
                <tr key={s.id} className="border-t border-slate-100 dark:border-slate-800">
                  <td className="py-1.5"><Link className="hover:underline" to={`/interview/${s.id}`}>{fmtDate(s.started_at, true)}</Link></td>
                  <td>{KIND_LABELS[s.kind]}</td>
                  <td><Badge tone={s.status === "completed" ? "green" : s.status === "active" ? "blue" : "slate"}>{s.status}</Badge></td>
                  <td>{s.num_questions}</td>
                  <td className="text-right font-medium tabular-nums">{s.overall_score ?? "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </Card>
    </div>
  );
}
